import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const rootDir = dirname(dirname(fileURLToPath(import.meta.url)));
const envPath = join(rootDir, '.env.local');
const outPath = join(rootDir, 'runtime-config.js');

// Maps a .env.local variable name to the window.CARBOYZ_* global the browser-side code reads it
// from (see chatFilterAdapter.js's resolveApiKey / locationAdapter.js's resolveApiKey).
const ENV_TO_WINDOW_GLOBAL = {
  ANTHROPIC_API_KEY: 'CARBOYZ_ANTHROPIC_API_KEY',
  GOOGLE_PLACES_API_KEY: 'CARBOYZ_GOOGLE_PLACES_API_KEY',
};

/** Minimal KEY=VALUE parser: skips blank lines and lines starting with '#', trims surrounding quotes. */
function parseEnvFile(text) {
  const values = {};
  for (const line of text.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const separatorIndex = trimmed.indexOf('=');
    if (separatorIndex === -1) continue;
    const key = trimmed.slice(0, separatorIndex).trim();
    let value = trimmed.slice(separatorIndex + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    if (key) values[key] = value;
  }
  return values;
}

/**
 * Generates the gitignored runtime-config.js the browser loads before App.js: sets
 * window.CARBOYZ_* globals from .env.local so static serving (no bundler/build step) can still
 * carry local secrets into the browser. Runs as `prestart` before `npx serve .`; a no-op (empty
 * output file) when .env.local is absent, so a fresh checkout still serves cleanly and every
 * adapter's existing no-key fallback path takes over.
 */
function main() {
  const envValues = existsSync(envPath) ? parseEnvFile(readFileSync(envPath, 'utf8')) : {};

  const assignments = Object.entries(ENV_TO_WINDOW_GLOBAL)
    .filter(([envKey]) => envValues[envKey])
    .map(([envKey, windowGlobal]) => `window.${windowGlobal} = ${JSON.stringify(envValues[envKey])};`);

  const header = '// Generated by scripts/generate-runtime-config.js — do not edit, do not commit.\n';
  writeFileSync(outPath, header + assignments.join('\n') + (assignments.length ? '\n' : ''));

  console.log(
    assignments.length
      ? `runtime-config.js written with ${assignments.length} key(s) from .env.local.`
      : 'runtime-config.js written (empty — no .env.local keys found).',
  );
}

main();
